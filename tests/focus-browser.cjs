const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  try {
    await page.clock.install();
    await page.goto(new URL('roam/', process.env.TEST_URL || 'http://127.0.0.1:3000/').href);
    await page.waitForFunction(() => window.__mischiefFocus && window.__buildlingsFrame);
    await page.locator('#focus-open').click();
    assert.equal(await page.locator('#stay-button').isDisabled(), true);
    await page.locator('#intention').fill('Finish the monkey app');
    await page.locator('#focus-minutes').fill('1');
    await page.getByRole('button', { name: 'Start my focus session' }).click();
    await page.locator('#session-controls').waitFor({ state: 'visible' });
    await page.clock.runFor(2100);
    const remaining = Number((await page.locator('#timer-clock').textContent()).split(':')[1]);
    assert.ok(remaining < 60 && remaining > 56);
    assert.equal(await page.locator('#session-intention').textContent(), 'Finish the monkey app');
    await page.locator('#stay-button').click();
    await page.clock.runFor(1600);
    assert.equal(await page.locator('#choice-count').textContent(), '1');
    assert.equal(await page.locator('#stay-button').isDisabled(), true);
    const quote = await page.evaluate(() => ({ text: document.querySelector('.bubble-words').textContent, author: document.querySelector('.bubble-author').textContent, actual: window.MischiefQuotes.hard.find(q => `— ${q.author}` === document.querySelector('.bubble-author').textContent && `“${q.text}”` === document.querySelector('.bubble-words').textContent) }));
    assert.ok(quote.actual, JSON.stringify(quote));
    assert.equal(await page.locator('#speech-bubble').evaluate(e => getComputedStyle(e).pointerEvents), 'none');
    await page.clock.runFor(2500); await page.locator('#stay-button').click();
    assert.equal(await page.locator('#choice-count').textContent(), '2');
    console.log('PASS running focus timer, recorded choices, accidental-click cooldown, and quote + name speech bubble');
    const thought = '<img src=x onerror=alert(1)> Remember this idea';
    await page.locator('#thought-input').fill(thought); await page.getByRole('button', { name: 'Keep this for later' }).click();
    assert.equal(await page.locator('#thought-list .thought-row > span').textContent(), thought);
    assert.equal(await page.locator('#thought-list img').count(), 0);
    await page.locator('#session-pause').click();
    const paused = await page.locator('#timer-clock').textContent(); await page.clock.runFor(60000);
    assert.equal(await page.locator('#timer-clock').textContent(), paused);
    assert.equal(await page.locator('#stay-button').isDisabled(), true);
    console.log('PASS paused time is excluded; saved thoughts render as text');
    await page.screenshot({ path: path.resolve('test-results/focus-desk.png') });
    await page.reload(); await page.waitForFunction(() => window.__mischiefFocus && window.__buildlingsFrame);
    await page.locator('#focus-open').click();
    assert.equal(await page.locator('#timer-clock').textContent(), paused);
    assert.equal(await page.locator('#session-pause').textContent(), 'Resume timer');
    assert.equal(await page.locator('#choice-count').textContent(), '2');
    assert.equal(await page.locator('#thought-list .thought-row > span').textContent(), thought);
    await page.locator('#session-pause').click(); await page.clock.runFor(60000);
    assert.equal(await page.locator('#session-summary').isVisible(), true);
    assert.equal(await page.locator('#summary-time').textContent(), '01:00');
    assert.equal(await page.locator('#summary-choices').textContent(), '2');
    assert.equal(await page.locator('#start-form').isVisible(), true);
    assert.equal(await page.evaluate(() => window.__mischiefFocus.history.length), 1);
    console.log('PASS reload recovery, preserved notes/choices, single completion, and session summary');
    await page.getByRole('button', { name: 'Take a break' }).click(); await page.clock.runFor(1000);
    assert.equal(await page.locator('#timer-label').textContent(), 'A little breathing room');
    assert.equal(await page.locator('#stay-button').isDisabled(), true);
    await page.locator('#session-end').click();
    await page.locator('.preferences-card > summary').click();
    await page.locator('#presence').selectOption('peek');
    await page.clock.runFor(10000);
    assert.ok(await page.evaluate(() => window.__buildlingsFrame.x > innerWidth - 30));
    assert.equal(await page.evaluate(() => window.__buildlingsFrame.mode), 'peek');
    await page.locator('.close-desk').click();
    await page.evaluate(() => window.companion.focusAction({ type: 'quote', category: 'hard' }));
    await page.clock.runFor(2000);
    const b = await page.locator('#speech-bubble').boundingBox(); assert.ok(b.x >= 0 && b.x + b.width <= 1440 && b.y >= 0);
    await page.screenshot({ path: path.resolve('test-results/monkey-peek-quote.png') });
    assert.equal(await page.evaluate(() => !!document.elementFromPoint(1420, window.__buildlingsFrame.y - 145)?.closest('#companion-host')), false);
    await page.locator('#focus-open').click(); await page.locator('#presence').selectOption('hidden');
    await page.clock.runFor(100);
    assert.equal(await page.locator('#companion-host').isVisible(), false);
    assert.equal(await page.locator('#speech-bubble').isVisible(), false);
    await page.locator('#presence').selectOption('wander'); await page.clock.runFor(5000);
    assert.equal(await page.locator('#companion-host').isVisible(), true);
    console.log('PASS break flow, screen-edge peeking, bubble bounds, click-through, complete hiding and return');
    await page.locator('#thought-list .thought-check').click();
    assert.equal(await page.locator('#done-list .thought-row').count(), 1);
    await page.locator('#done-thoughts > summary').click(); await page.locator('#done-list .thought-remove').click();
    assert.equal(await page.evaluate(() => window.__mischiefFocus.notes.length), 0);
    for (const width of [320, 390, 768]) {
      await page.setViewportSize({ width, height: 900 }); await page.clock.runFor(100);
      assert.equal(await page.locator('#focus-desk').evaluate(e => e.scrollWidth <= e.clientWidth), true);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    }
    assert.deepEqual(errors, []);
    console.log('PASS thought review/removal and focus controls at 320px, 390px and 768px');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
